package com.github.ifrugal.gateway.core.config;

import jakarta.validation.constraints.NotBlank;
import lombok.Data;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.validation.annotation.Validated;

/**
 * Configuration properties for request-id handling.
 *
 * <p>Every request passing through the gateway gets exactly one request id.
 * An inbound id is kept only if it fully matches {@link #pattern}; otherwise
 * (missing, blank, too short/long, unexpected characters) it is replaced by a
 * random UUID. The final id is forwarded downstream, echoed on every response,
 * stored as an exchange attribute, written to the Reactor Context and, when
 * {@link #contextPropagation} is on, bridged to the SLF4J MDC.</p>
 *
 * Example configuration:
 * <pre>
 * gateway:
 *   request-id:
 *     header-name: x-request-id
 *     pattern: "^[A-Za-z0-9._-]{8,64}$"
 *     mdc-key: requestId
 *     context-propagation: true
 * </pre>
 */
@ConfigurationProperties(prefix = "gateway.request-id")
@Validated
@Data
public class RequestIdProperties {

    /**
     * Default request-id header name.
     */
    public static final String DEFAULT_HEADER_NAME = "x-request-id";

    /**
     * Default validation pattern for inbound request ids: 8 to 64 characters
     * from a conservative, log-safe and header-safe alphabet.
     */
    public static final String DEFAULT_PATTERN = "^[A-Za-z0-9._-]{8,64}$";

    /**
     * Default SLF4J MDC key.
     */
    public static final String DEFAULT_MDC_KEY = "requestId";

    /**
     * Header carrying the request id, both inbound and on the response.
     * Matching is case-insensitive.
     */
    @NotBlank(message = "gateway.request-id.header-name must not be blank")
    private String headerName = DEFAULT_HEADER_NAME;

    /**
     * Regular expression an inbound request id must fully match to be kept.
     * Ids generated by the gateway are always random UUIDs, regardless of this pattern.
     */
    @NotBlank(message = "gateway.request-id.pattern must not be blank")
    private String pattern = DEFAULT_PATTERN;

    /**
     * SLF4J MDC key the request id is exposed under in log events.
     */
    @NotBlank(message = "gateway.request-id.mdc-key must not be blank")
    private String mdcKey = DEFAULT_MDC_KEY;

    /**
     * Register the MDC bridge with Micrometer context-propagation and enable
     * Reactor automatic context propagation so every log line written while
     * the request is processed carries the request id in the MDC.
     */
    private boolean contextPropagation = true;
}
